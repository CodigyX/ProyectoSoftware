    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
       try {
        JSONObject json = new JSONObject();
        json.put("txtClave", txtIngresarBuscar.getText());

        String response = sendHttpRequest("buscar", json);

        // Parsear la respuesta JSON
        JSONObject jsonResponse = new JSONObject(response);
        String mensaje = jsonResponse.getString("mensaje");

        // Obtener los datos del material (adaptar según la estructura de la respuesta)
        JSONArray materiales = jsonResponse.getJSONArray("materiales");

        // Limpiar la tabla
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        // Agregar los materiales a la tabla
        for (int i = 0; i < materiales.length(); i++) {
            JSONObject material = materiales.getJSONObject(i);
            model.addRow(new Object[]{
                material.getString("clave"),
                material.getString("nombre"),
                material.getString("descripcion"),
                material.getString("unidadMedida"),
                material.getInt("existencia")
            });
        }

        JOptionPane.showMessageDialog(this, mensaje);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al buscar el material: " + e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_btnBuscarActionPerformed

